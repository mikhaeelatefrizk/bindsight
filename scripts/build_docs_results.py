"""Generate docs/results.md from the committed benchmark results.

The documentation site and the Streamlit app must never disagree about what
bindsight has actually demonstrated, so both read the same source:
``bindsight.report.showcase``.

The output is committed so that ``mkdocs serve`` works from a fresh clone.
``tests/test_docs_results.py`` asserts the committed file still matches what
this script produces, which turns any drift into a test failure rather than a
stale claim on a public page.

Regenerate with:

    python scripts/build_docs_results.py
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path
from typing import Any

from bindsight.report import showcase, theme

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
OUT_MD = DOCS / "results.md"
OUT_GLOSSARY = DOCS / "glossary.md"
FIG_DIR = DOCS / "assets" / "figures"

BANNER = "<!-- Generated by scripts/build_docs_results.py — do not edit by hand. -->"


def build_glossary() -> str:
    """Render docs/glossary.md from ``theme.GLOSSARY`` (the app's source too).

    Single source of truth: the Streamlit app's Glossary page and this docs
    page render the same ``theme.GLOSSARY``, so a term added or reworded in one
    place appears in both.
    """
    lines = [
        "---",
        "title: Glossary",
        "description: >-",
        "  Plain-English definitions of the terms bindsight uses — RNA-seq,",
        "  surfaceome, de novo binder, ipTM, PAE and more — for readers new to",
        "  genomics or protein design.",
        "---",
        "",
        BANNER,
        "",
        "# Glossary",
        "",
        "Every specialist term bindsight uses, in plain language. If a word",
        "elsewhere in these docs or the app is unfamiliar, it is almost certainly",
        "defined here.",
        "",
        f'!!! info "In plain terms"\n    {theme.PLAIN_SUMMARY}',
        "",
    ]
    for term, definition in theme.GLOSSARY:
        lines.append(f"**{term}**")
        lines.append(f": {definition}")
        lines.append("")
    return "\n".join(lines)


def _mean_iptm(d: Any) -> str:
    """Mean ipTM from the artifact, so the prose cannot outlive the run."""
    value = d.mean_iptm
    return f"{value:.2f}" if value is not None else "unavailable"


def _best_iptm(d: Any) -> str:
    """Best ipTM from the artifact, for the same reason."""
    best = d.best
    return f"{best.iptm:.2f}" if best is not None and best.iptm is not None else "unavailable"


def _fmt(value: object, spec: str = "") -> str:
    """Format a number for a docs table, rendering ``None`` as an em dash."""
    if value is None:
        return "—"
    if spec:
        return f"{value:{spec}}"
    return str(value)


def _study_section(st: showcase.StudyShowcase) -> list[str]:
    """Render the rediscovery-study section.

    Every rate is printed with its numerator, denominator and interval, and every
    rank with the size of the list it sits in. The previous version of this page
    quoted "ERBB2 rediscovered at rank 4" and "recall@5 = 33%" without either.
    """
    lines: list[str] = [
        "## Does it rediscover antigens we already trust?",
        "",
        f"**{st.n_scored} antigen-cohort pairs across {st.n_projects} real TCGA projects.** "
        "Each cohort is a whole, unstratified project — every primary tumour against "
        "every solid-tissue normal — with the contrast paired on the patient. Nothing "
        "selects for the antigen being sought.",
        "",
        "The earlier version of this study did select for it: it chose breast tumours "
        "by a subtype classifier built on fifty genes, one of them ERBB2, and then "
        "reported discovering ERBB2. The numbers below are far weaker, and they are "
        "the honest ones.",
        "",
    ]

    top = st.headline
    if top is not None:
        lines += [
            f"The best-ranked antigen is **{top['symbol']}** in "
            f"{str(top['project']).removeprefix('TCGA-')}, at rank **{top['rank']} of "
            f"{top['shortlist_size']}** candidates, with a log2 fold change of "
            f"{top['log2fc']:.2f}.",
            "",
        ]

    block = st.recall_cascade.get("all") or {}
    at_k = block.get("at_k") or {}
    if at_k:
        lines += [
            "### Recall, approved agents only",
            "",
            "An absolute cutoff is only comparable between shortlists of similar size, "
            f"so the median shortlist here is **{block.get('median_shortlist_size', '—')}** "
            f"candidates drawn from a surfaceome of {st.surfaceome_size:,} accessions.",
            "",
            "| Cutoff | Surfaced | 95% CI |",
            "|---|--:|---|",
        ]
        for cutoff, entry in at_k.items():
            w = entry.get("wilson") or {}
            lines.append(
                f"| {cutoff} | {w.get('numerator')}/{w.get('denominator')} | "
                f"{w.get('low', 0):.3f}–{w.get('high', 0):.3f} |"
            )
        lines.append("")

    sensitivity = (st.tier_sensitivity or {}).get("at_k") or {}
    if sensitivity:
        lines += [
            "### Sensitivity to the regulatory tier",
            "",
            "The headline counts only antigens whose targeting agent is approved. That "
            "excludes CA9 and GPC3, whose evidence is strong and whose agents are not "
            "yet licensed. Widening the panel is reported separately rather than folded "
            "in, because choosing a denominator after seeing the data is what made the "
            "earlier study untrustworthy.",
            "",
            "| Cutoff | Every scored pair |",
            "|---|--:|",
        ]
        for cutoff, w in sensitivity.items():
            lines.append(f"| {cutoff} | {w.get('numerator')}/{w.get('denominator')} |")
        lines.append("")

    counts = st.outcome_counts or {}
    if counts:
        lines += [
            "### Four outcomes, never merged",
            "",
            "An antigen the surfaceome reference does not contain, one a stated filter "
            "excluded, one the ranking placed low, and one whose lookup failed are four "
            "different findings about four different parts of the system.",
            "",
            "| Outcome | Pairs |",
            "|---|--:|",
            f"| Reached the shortlist | {counts.get('ranked', 0)} |",
            f"| Excluded by a stated filter | {counts.get('gated_out', 0)} |",
            f"| Outside the instrument's reach | {counts.get('not_reachable', 0)} |",
            f"| Invalid, must be re-run | {counts.get('infrastructure', 0)} |",
            "",
        ]

    rows = st.rows()
    if rows:
        lines += [
            "### Every pair",
            "",
            "| Antigen | Cohort | log2FC | padj | Rank | Counterfactual rank | Why |",
            "|---|---|--:|--:|--:|--:|---|",
        ]
        for r in rows:
            rank = f"{r['rank']} of {r['shortlist']}" if r["rank"] is not None else "—"
            cf = (
                f"{r['counterfactual_rank']} of {r['eligible']}"
                if r["counterfactual_rank"] is not None
                else "—"
            )
            log2fc = f"{r['log2fc']:.2f}" if r["log2fc"] is not None else "—"
            padj = f"{r['padj']:.2e}" if r["padj"] is not None else "—"
            lines.append(
                f"| **{r['antigen']}** | {r['cohort']} | {log2fc} | {padj} | {rank} | "
                f"{cf} | {r['why']} |"
            )
        lines.append("")

    if st.design.get("unreachable_note"):
        lines += [
            "### Antigens the instrument could not see",
            "",
            st.design["unreachable_note"],
            "",
        ]

    for name, caption in (
        (
            "surfaced_ranks",
            "Where each surfaced antigen ranked, drawn against the shortlist it was ranked within.",
        ),
        (
            "outcome_classes",
            "The four outcomes, reported separately. Collapsing them into one recall "
            "number is what made the previous page misleading.",
        ),
    ):
        if name in st.figures:
            lines += [f"![{caption}](assets/figures/{name}.png)", "", f"*{caption}*", ""]
    return lines


def _designer_section(d: showcase.DesignerShowcase) -> list[str]:
    """Render the designer-benchmark section."""
    lines = [
        "## The binders it actually designed",
        "",
        f"A **real GPU run**, not a simulation — backend `{d.backend}`, GPU `{d.gpu}`, "
        f"validator `{d.validator}`, bindsight `{d.bindsight_version}`, "
        f"{d.generated_utc[:10]}.",
        "",
        '!!! success "The target was held fixed, and that is checked"',
        "",
        "    An earlier run invoked ProteinMPNN without `--pdb_path_chains`, so the",
        "    sequence designer rewrote the antigen as well as the binder: those binders",
        "    were optimised against a partly-invented ERBB2 surface and then scored",
        "    against the native one. Its figures — best ipTM 0.84, 50% success — are",
        "    withdrawn.",
        "",
        "    The run below uses the corrected protocol, and every design carries a",
        "    target chain byte-identical to the native 142-residue domain IV. The",
        f"    corrected mean ipTM is *lower* than the superseded one, {_mean_iptm(d)}",
        "    against 0.59, which is what you would expect once designs stop being",
        "    scored against a surface they helped invent. The best single design is",
        f"    better: {_best_iptm(d)}.",
        "",
    ]
    if d.targets:
        lines += [f"**Target:** {d.targets[0]}", ""]

    best = d.best
    stats = [(str(d.n_designs), "designs", "RFdiffusion → ProteinMPNN → Boltz-2")]
    if best is not None and best.iptm is not None:
        stats.append((f"{best.iptm:.2f}", "best ipTM", f"design {best.binder_id}"))
    if d.success_rate is not None:
        interval = d.success_interval
        note = "standard criterion"
        if interval is not None:
            # Never a bare rate: the interval is clustered over backbones,
            # because designs sharing a trajectory are not independent trials.
            note = f"95% CI {interval[0] * 100:.0f}–{interval[1] * 100:.0f}% over backbones"
        stats.append((f"{d.success_rate * 100:.0f}%", "success @ ipTM 0.65", note))
    paes = [b.pae_interaction for b in d.binders if b.pae_interaction is not None]
    if paes:
        stats.append((f"{sum(paes) / len(paes):.1f} Å", "mean PAE-int", "lower is more confident"))

    lines += ['<div class="bs-stats">']
    lines += [
        f'<div class="bs-stat"><div class="v">{val}</div>'
        f'<div class="k">{key}</div><div class="d">{detail}</div></div>'
        for val, key, detail in stats
    ]
    lines += ["</div>", ""]

    lines += [
        "The real Boltz-2 predicted complex behind every ipTM below is committed",
        "alongside its metrics. Rotate them in 3-D on the",
        f"[live app]({showcase_hf()}) → **Real results**.",
        "",
        "| design | ipTM | PAE-int (Å) | developability | length | instability |",
        "|---|--:|--:|--:|--:|--:|",
    ]
    for b in d.scored:
        dev = b.developability
        lines.append(
            f"| `{b.binder_id}` | {_fmt(b.iptm, '.3f')} | {_fmt(b.pae_interaction, '.1f')} "
            f"| {_fmt(dev.get('developability_score'), '.2f')} "
            f"| {_fmt(dev.get('length'), '.0f')} "
            f"| {_fmt(dev.get('instability_index'), '.1f')} |"
        )
    lines.append("")
    return lines


def showcase_hf() -> str:
    """Return the primary hosted-app URL."""
    from bindsight.report import theme

    return theme.HF_SPACE_URL


def _copy_figures(v: showcase.StudyShowcase | None) -> int:
    """Copy benchmark figures into the docs tree.

    MkDocs can only serve files beneath ``docs_dir``, and ``benchmarks/`` sits
    outside it. Copies rather than symlinks so the build works on Windows and
    inside the Pages runner.

    Args:
        v: Loaded study results, or ``None``.

    Returns:
        Number of figures copied.
    """
    if v is None or not v.figures:
        return 0
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    for name, src in v.figures.items():
        shutil.copyfile(src, FIG_DIR / f"{name}.png")
    return len(v.figures)


def build() -> str:
    """Render the full results page as Markdown."""
    study = showcase.load_study()
    designer = showcase.load_designer_benchmark()

    lines = [
        "---",
        "title: Real results",
        "description: >-",
        "  What bindsight has actually demonstrated: rediscovery of clinically",
        "  validated antigens from real TCGA cohorts, and 20 de novo ERBB2 binders",
        "  designed and validated end-to-end on a free GPU.",
        "---",
        "",
        BANNER,
        "",
        "# Real results",
        "",
        "Everything on this page is read straight from `benchmarks/` in the",
        "repository — the same files the paper and the README cite. Nothing here is",
        "illustrative, recomputed on the fly, or hand-typed.",
        "",
    ]

    if study is not None:
        lines += _study_section(study)
    if designer is not None:
        lines += _designer_section(designer)

    lines += [
        "## Reproduce it",
        "",
        "```bash",
        'pip install -e ".[discover,report]"',
        "python benchmarks/run_study.py --all --cpus 2  # rediscovery study",
        "python benchmarks/designer_benchmark/score_run.py   # designer benchmark",
        "```",
        "",
        "Full write-ups, including the caveats, live in",
        "[`benchmarks/study/RESULTS.md`](https://github.com/mikhaeelatefrizk/bindsight/blob/main/benchmarks/study/RESULTS.md)",
        "and",
        "[`benchmarks/designer_benchmark/RESULTS.md`](https://github.com/mikhaeelatefrizk/bindsight/blob/main/benchmarks/designer_benchmark/RESULTS.md).",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    """Write docs/results.md and copy the figures it references."""
    study = showcase.load_study()
    if study is None and showcase.load_designer_benchmark() is None:
        print("benchmarks/ not found — nothing to build", file=sys.stderr)
        return 1

    n = _copy_figures(study)
    OUT_MD.write_text(build(), encoding="utf-8")
    OUT_GLOSSARY.write_text(build_glossary(), encoding="utf-8")
    print(
        f"wrote {OUT_MD.relative_to(ROOT)} + {OUT_GLOSSARY.relative_to(ROOT)} "
        f"and copied {n} figure(s)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
