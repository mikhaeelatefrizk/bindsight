def build_glossary() -> str:
    """Render docs/glossary.md from ``theme.GLOSSARY``.

    ``theme.GLOSSARY`` holds the project's vocabulary and this is its only
    renderer -- the served interface has no glossary page. It lives in the
    package rather than beside this script so the terms travel with the
    software that uses them, and so a reader who has the package has the
    definitions.

    This docstring used to claim a single source of truth shared with the
    Streamlit app's Glossary page, on the grounds that a term reworded in one
    place appeared in both. Both halves stopped being true when that app was
    removed.
    """
    lines = [
        "---",
        "title: Glossary",
        "description: >-",
        "  Plain-English definitions of the terms bindsight uses — RNA-seq,",
        "  surfaceome, de novo binder, ipTM, PAE and more — for readers new to",
        "  genomics or protein design.",
        "---",
        "",
        BANNER,
        "",
        "# Glossary",
        "",
        "Every specialist term bindsight uses, in plain language. If a word",
        "elsewhere in these docs or the app is unfamiliar, it is almost certainly",
        "defined here.",
        "",
        f'!!! info "In plain terms"\n    {theme.PLAIN_SUMMARY}',
        "",
    ]
    for term, definition in theme.GLOSSARY:
        lines.append(f"**{term}**")
        lines.append(f": {definition}")
        lines.append("")
    return "\n".join(lines)


def _mean_iptm_interval(d: Any) -> tuple[float, float, float] | None:
    """Mean ipTM with a normal-approximation interval, from the binders themselves.

    The page compared this mean against a superseded run's and called the
    difference "what you would expect". Two means from twenty designs each are
    not distinguishable at this spread, and saying so is the difference between
    reporting a measurement and reporting a preference.
    """
    import math
    import statistics

    values = [b.iptm for b in d.binders if getattr(b, "iptm", None) is not None]
    if len(values) < 2:
        return None
    mean = statistics.fmean(values)
    half = 1.959963985 * statistics.stdev(values) / math.sqrt(len(values))
    return mean, mean - half, mean + half


def _mean_iptm(d: Any) -> str:
    """Mean ipTM from the artifact, so the prose cannot outlive the run."""
    value = d.mean_iptm
    return f"{value:.2f}" if value is not None else "unavailable"


def _best_iptm(d: Any) -> str:
    """Best ipTM from the artifact, for the same reason."""
    best = d.best
    return f"{best.iptm:.2f}" if best is not None and best.iptm is not None else "unavailable"


def _fmt(value: object, spec: str = "") -> str:
    """Format a number for a docs table, rendering ``None`` as an em dash."""
    if value is None:
        return "—"
    if spec:
        return f"{value:{spec}}"
    return str(value)


def _nulls_section(st: showcase.StudyShowcase) -> list[str]:
    """Both null models, with the positive and the negative given equal room.

    Until this existed neither reached a reader. The decoy null -- the study's
    own primary null, and a negative -- and the indication-specificity null --
    the strongest claim the study supports -- lived only in
    ``benchmarks/study/RESULTS.md``, absent from every README, docs page and
    manuscript. A project whose credibility rests on volunteering disconfirming
    evidence was volunteering it in one file.
    """
    spec = st.specificity_null
    gap = st.indication_gap
    if not spec and not st.decoy_rows:
        return []

    lines: list[str] = [
        "### Is the ranking doing anything? Two nulls, pointing different ways",
        "",
        "Both are reported because reporting only the flattering one would make "
        "the other the finding.",
        "",
    ]

    if st.decoy_rows:
        nominal = st.decoy_nominal
        survived = st.decoy_surviving_correction
        bound = st.smallest_attainable_decoy_bh
        lines += [
            "**Against matched decoys — negative.** Each antigen is compared with "
            "genes matched to it on abundance and dispersion quintile, drawn from the "
            "same eligible surfaceome and ranked by the same counterfactual score: "
            "would a gene that merely *looks* like this antigen have ranked as well? "
            f"Of {len(st.decoy_rows)} pairs, **{nominal} are nominally significant at "
            f"0.05 and {survived} survive Benjamini-Hochberg** across the panel. "
            "Against background matched this way, no antigen here is distinguishable "
            "once the panel is corrected for its own size.",
            "",
        ]
        if bound is not None:
            lines += [
                "Read that with the panel's resolution in mind. Each pair's p is "
                "bounded below by the size of its own decoy stratum, so the smallest "
                f"BH-adjusted value this panel could have produced is **{bound:.3f}** "
                "— under 0.05, so a pair genuinely could have survived, but only one "
                "sitting essentially on its floor. The negative is a measurement, not "
                "a foregone conclusion; it is also not a sensitive one.",
                "",
            ]

    if spec:
        observed = spec.get("observed")
        p_value = spec.get("p_value")
        n_perm = spec.get("n_permutations")
        n_antigens = spec.get("n_antigens")
        n_cohorts = spec.get("n_cohorts")
        lines += [
            "**Against a permuted indication — positive.** A narrower panel than the "
            "decoy null above, ranked in the cancer each antigen is actually used in "
            "against a permuted assignment to the other cohorts. This asks a "
            "different question: not whether any single antigen beats its lookalikes, "
            "but whether the ordering knows which disease it is looking at.",
            "",
        ]
        if observed is not None and p_value is not None:
            floor_note = (
                " — the floor for this many permutations, so it is as extreme as an "
                "exhaustive enumeration of this panel can show rather than vanishingly "
                "small"
                if st.specificity_is_at_its_floor
                else ""
            )
            # The denominator, stated with the p-value rather than left to the
            # reader. It is narrower than the decoy null's directly above, and
            # this page was the one surface quoting the p-value without saying
            # so -- the README, docs/what-is-bindsight.md and the study's own
            # RESULTS.md all name the restriction inline. The count is read
            # from the study rather than written here, so it cannot drift.
            lines += [
                f"- Computed over **{n_antigens} antigens**"
                + (f" of the {len(st.decoy_rows)} pairs above" if st.decoy_rows else "")
                + f", across {n_cohorts} cohorts — those carrying a single "
                "indication. The test assigns one cohort per antigen, so an antigen "
                "licensed in several cancers has no single correct one to permute "
                "and cannot enter it",
                f"- Observed mean standing **{observed:.3f}**, where 1.0 is the top of "
                "the eligible surfaceome and 0.0 the bottom",
                f"- p = **{p_value:.2e}** over {n_perm} enumerated permutations{floor_note}",
            ]
        if gap.get("point") is not None:
            lines += [
                f"- Within-antigen difference **{gap['point']:.3f}** "
                f"(95% CI {gap['low']:.3f}–{gap['high']:.3f}) between an antigen's "
                "standing in its own indication and in cohorts carrying no panel "
                "antigen — each antigen is its own control, and the interval excludes "
                "zero",
            ]
        lines += [
            "",
            "This is the strongest claim the study supports, and it is a claim about "
            "the ordering, not about any individual hit.",
            "",
        ]

    return lines


def _study_section(st: showcase.StudyShowcase) -> list[str]:
    """Render the rediscovery-study section.

    Every rate is printed with its numerator, denominator and interval, and every
    rank with the size of the list it sits in. The previous version of this page
    quoted "ERBB2 rediscovered at rank 4" and "recall@5 = 33%" without either.
    """
    lines: list[str] = [
        "## Does it rediscover antigens we already trust?",
        "",
        f"**{st.n_scored} antigen-cohort pairs across {st.n_projects} real TCGA projects.** "
        "Each cohort is a whole, unstratified project — every primary tumour against "
        "every solid-tissue normal — with the contrast paired on the patient. Nothing "
        "selects for the antigen being sought.",
        "",
        "The earlier version of this study did select for it: it chose breast tumours "
        "by a subtype classifier built on fifty genes, one of them ERBB2, and then "
        "reported discovering ERBB2. The numbers below are far weaker, and they are "
        "the honest ones.",
        "",
    ]

    top = st.headline
    if top is not None:
        lines += [
            f"The best-ranked antigen is **{top['symbol']}** in "
            f"{str(top['project']).removeprefix('TCGA-')}, at rank **{top['rank']} of "
            f"{top['shortlist_size']}** candidates, with a log2 fold change of "
            f"{top['log2fc']:.2f}.",
            "",
        ]

    block = st.recall_cascade.get("all") or {}
    at_k = block.get("at_k") or {}
    if at_k:
        lines += [
            "### Recall, approved agents only",
            "",
            "An absolute cutoff is only comparable between shortlists of similar size, "
            f"so the median shortlist here is **{block.get('median_shortlist_size', '—')}** "
            f"candidates drawn from a surfaceome of {st.surfaceome_size:,} accessions.",
            "",
            "| Cutoff | Surfaced | 95% CI |",
            "|---|--:|---|",
        ]
        for cutoff, entry in at_k.items():
            w = entry.get("wilson") or {}
            lines.append(
                f"| {cutoff} | {w.get('numerator')}/{w.get('denominator')} | "
                f"{w.get('low', 0):.3f}–{w.get('high', 0):.3f} |"
            )
        lines.append("")

    sensitivity = (st.tier_sensitivity or {}).get("at_k") or {}
    if sensitivity:
        lines += [
            "### Sensitivity to the regulatory tier",
            "",
            "The headline counts only antigens whose targeting agent is approved. That "
            "excludes CA9 and GPC3, whose evidence is strong and whose agents are not "
            "yet licensed. Widening the panel is reported separately rather than folded "
            "in, because choosing a denominator after seeing the data is what made the "
            "earlier study untrustworthy.",
            "",
            "| Cutoff | Every scored pair |",
            "|---|--:|",
        ]
        for cutoff, w in sensitivity.items():
            lines.append(f"| {cutoff} | {w.get('numerator')}/{w.get('denominator')} |")
        lines.append("")

    lines += _nulls_section(st)

    # Both frames, side by side. A single unlabelled column of the
    # approved-only counts read as a total of the pair table printed below it.
    counts = st.outcome_counts or {}
    every = st.outcome_counts_every_tier
    if counts:
        lines += [
            "### Four outcomes, never merged",
            "",
            "An antigen the surfaceome reference does not contain, one a stated filter "
            "excluded, one the ranking placed low, and one whose lookup failed are four "
            "different findings about four different parts of the system. The first "
            "column is the pre-registered approved-agent denominator; the second is "
            "every scored pair, matching the table below.",
            "",
            "| Outcome | Approved agents | Every scored pair |",
            "|---|--:|--:|",
            f"| Reached the shortlist | {counts.get('ranked', 0)} | {every.get('ranked', 0)} |",
            f"| Excluded by a stated filter | {counts.get('gated_out', 0)} | "
            f"{every.get('gated_out', 0)} |",
            f"| Outside the instrument's reach | {counts.get('not_reachable', 0)} | "
            f"{every.get('not_reachable', 0)} |",
            f"| Invalid, must be re-run | {counts.get('infrastructure', 0)} | "
            f"{every.get('infrastructure', 0)} |",
            "",
        ]

    rows = st.rows()
    if rows:
        lines += [
            "### Every pair",
            "",
            "| Antigen | Cohort | log2FC | padj | Rank | Counterfactual rank | Why |",
            "|---|---|--:|--:|--:|--:|---|",
        ]
        for r in rows:
            rank = f"{r['rank']} of {r['shortlist']}" if r["rank"] is not None else "—"
            cf = (
                f"{r['counterfactual_rank']} of {r['eligible']}"
                if r["counterfactual_rank"] is not None
                else "—"
            )
            log2fc = f"{r['log2fc']:.2f}" if r["log2fc"] is not None else "—"
            padj = f"{r['padj']:.2e}" if r["padj"] is not None else "—"
            lines.append(
                f"| **{r['antigen']}** | {r['cohort']} | {log2fc} | {padj} | {rank} | "
                f"{cf} | {r['why']} |"
            )
        lines.append("")

    if st.design.get("unreachable_note"):
        lines += [
            "### Antigens the instrument could not see",
            "",
            st.design["unreachable_note"],
            "",
        ]

    for name, caption in (
        (
            "surfaced_ranks",
            "Where each surfaced antigen ranked, drawn against the shortlist it was ranked within.",
        ),
        (
            "outcome_classes",
            "The four outcomes, reported separately. Collapsing them into one recall "
            "number is what made the previous page misleading.",
        ),
    ):
        if name in st.figures:
            lines += [f"![{caption}](assets/figures/{name}.png)", "", f"*{caption}*", ""]
    return lines


def _designer_section(d: showcase.DesignerShowcase) -> list[str]:
    """Render the designer-benchmark section."""
    lines = [
        "## The binders it actually designed",
        "",
        # Derived from the artifact's own is_mock flag, not asserted. This
        # sentence was a literal, so regenerating the page from a mock run — one
        # that installs nothing and runs no GPU — would have published synthetic
        # numbers under the words "not a simulation".
        (
            f"A **real GPU run**, not a simulation — backend `{d.backend}`, GPU `{d.gpu}`, "
            f"validator `{d.validator}`, bindsight `{d.bindsight_version}`, "
            f"{d.generated_utc[:10]}."
            if d.is_mock is False
            else f"⚠️ **Synthetic output from the mock backend** — no GPU ran and no tool "
            f"was installed. Backend `{d.backend}`, bindsight `{d.bindsight_version}`, "
            f"{d.generated_utc[:10]}. These numbers are for orchestration testing only."
            if d.is_mock
            else f"Backend `{d.backend}`, GPU `{d.gpu}`, validator `{d.validator}`, "
            f"bindsight `{d.bindsight_version}`, {d.generated_utc[:10]}. The artifact "
            "does not record whether a real GPU ran."
        ),
        "",
        '!!! success "The target was held fixed, and that is checked"',
        "",
        "    An earlier run invoked ProteinMPNN without `--pdb_path_chains`, so the",
        "    sequence designer rewrote the antigen as well as the binder: those binders",
        "    were optimised against a partly-invented ERBB2 surface and then scored",
        "    against the native one. Its figures — best ipTM 0.84, 50% success — are",
        "    withdrawn.",
        "",
        "    The run below uses the corrected protocol, and every design carries a",
        "    target chain byte-identical to the native 142-residue domain IV. The",
        f"    corrected mean ipTM is {_mean_iptm(d)} against the superseded 0.59"
        + (
            f", but the two are not distinguishable at this size: the interval on"
            f" this mean is {_ci[1]:.2f}–{_ci[2]:.2f} and 0.59 falls inside it."
            if (_ci := _mean_iptm_interval(d)) and _ci[1] <= 0.59 <= _ci[2]
            else "."
        ),
        "    The protocol correction rests on the chain-identity check below, not",
        f"    on the means moving. The best single design is {_best_iptm(d)}.",
        "",
    ]
    if d.targets:
        lines += [f"**Target:** {d.targets[0]}", ""]

    best = d.best
    stats = [(str(d.n_designs), "designs", "RFdiffusion → ProteinMPNN → Boltz-2")]
    if best is not None and best.iptm is not None:
        stats.append((f"{best.iptm:.2f}", "best ipTM", f"design {best.binder_id}"))
    if d.success_rate is not None:
        interval = d.success_interval
        note = "standard criterion"
        if interval is not None:
            # Never a bare rate: the interval is clustered over backbones,
            # because designs sharing a trajectory are not independent trials.
            note = f"95% CI {interval[0] * 100:.0f}–{interval[1] * 100:.0f}% over backbones"
        # The caveat rides on the stat itself. This is the most-read surface the
        # rate appears on, and a reader who sees only the tile sees the one
        # thing the calibration showed it does not support.
        note += " — withdrawn as a measure of design quality"
        stats.append((f"{d.success_rate * 100:.0f}%", "success @ ipTM 0.65", note))
    paes = [b.pae_interaction for b in d.binders if b.pae_interaction is not None]
    if paes:
        stats.append((f"{sum(paes) / len(paes):.1f} Å", "mean PAE-int", "lower is more confident"))

    lines += ['<div class="bs-stats">']
    lines += [
        f'<div class="bs-stat"><div class="v">{val}</div>'
        f'<div class="k">{key}</div><div class="d">{detail}</div></div>'
        for val, key, detail in stats
    ]
    lines += ["</div>", ""]

    # This paragraph has pointed readers at two things that were not here: a
    # page the removed app had, and then the hosted build -- a promise this
    # repository cannot keep on its own, because the Space serves whatever it
    # last received. Now it points at nothing. The complexes are drawn on this
    # page, from files in this repository, by a viewer served beside them.
    lines += [
        "The real Boltz-2 predicted complex behind every ipTM in the table below",
        "is committed alongside its metrics — and drawn here, in your browser,",
        "from those files. No install, no server, nothing uploaded.",
        "",
    ]
    lines += _viewer_block(d)
    lines += [
        "Ordered by interface confidence, best first; the corrected-protocol ipTM",
        "for each is in the table below.",
        "",
        "Every complex is also browsable as mmCIF in",
        "[benchmarks/designer_benchmark/binders/]"
        "(https://github.com/mikhaeelatefrizk/bindsight/tree/main/benchmarks/designer_benchmark/binders),",
        "which is the file this viewer reads.",
        "",
    ]
    lines += [
        "| design | ipTM | PAE-int (Å) | developability | length | instability |",
        "|---|--:|--:|--:|--:|--:|",
    ]
    for b in d.scored:
        dev = b.developability
        lines.append(
            f"| `{b.binder_id}` | {_fmt(b.iptm, '.3f')} | {_fmt(b.pae_interaction, '.1f')} "
            f"| {_fmt(dev.get('developability_score'), '.2f')} "
            f"| {_fmt(dev.get('length'), '.0f')} "
            f"| {_fmt(dev.get('instability_index'), '.1f')} |"
        )
    lines.append("")
    return lines


