def main() -> int:
    """Write docs/results.md and copy the figures it references."""
    study = showcase.load_study()
    if study is None and showcase.load_designer_benchmark() is None:
        print("benchmarks/ not found — nothing to build", file=sys.stderr)
        return 1

    n = _copy_assets(study, showcase.load_designer_benchmark())
    OUT_MD.write_text(build(), encoding="utf-8", newline="\n")
    OUT_GLOSSARY.write_text(build_glossary(), encoding="utf-8", newline="\n")
    print(
        f"wrote {OUT_MD.relative_to(ROOT)} + {OUT_GLOSSARY.relative_to(ROOT)}; copied "
        f"{n['figures']} figure(s), {n['structures']} structure(s), "
        f"{n['vendor']} vendored file(s), {n['scripts']} script(s)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
