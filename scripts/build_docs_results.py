def _copy_assets(
    v: showcase.StudyShowcase | None, d: showcase.DesignerShowcase | None
) -> dict[str, int]:
    """Mirror everything the published pages need beneath ``docs_dir``.

    MkDocs can only serve files beneath ``docs_dir``, and both ``benchmarks/``
    and the package's own ``web/static`` sit outside it. Copies rather than
    symlinks so the build works on Windows and inside the Pages runner.

    Copies *bytes*, never text. ``.gitattributes`` checks these files out with
    LF, and a text round-trip on Windows would write them back with CRLF --
    leaving ``git diff`` dirty on every machine that ran the generator.

    Every copy is byte-identical to its source. That is not incidental: git is
    content-addressed, so an identical copy costs a tree entry rather than
    another 2.8 MB of pack, and ``tests/test_docs_binder_viewer.py`` asserts
    the identity that makes it true.

    Args:
        v: Loaded study results, or ``None``.
        d: Loaded designer benchmark, or ``None``.

    Returns:
        A count per asset kind.
    """
    counts = {"figures": 0, "structures": 0, "vendor": 0, "scripts": 0}

    # The scripts the published pages load. Mirrored unconditionally: the
    # data checker's page has nothing to do with the benchmark, so gating it
    # on the benchmark being present would drop it from a checkout that has
    # the page but not the artifacts.
    JS_DIR.mkdir(parents=True, exist_ok=True)
    for name in ("binder_viewer.js", "your_data_check.js"):
        shutil.copyfile(WEB_STATIC / name, JS_DIR / name)
        counts["scripts"] += 1

    if v is not None and v.figures:
        FIG_DIR.mkdir(parents=True, exist_ok=True)
        for name, src in v.figures.items():
            shutil.copyfile(src, FIG_DIR / f"{name}.png")
        counts["figures"] = len(v.figures)

    structures = d.with_structures() if d is not None else []
    if not structures:
        return counts

    STRUCT_DIR.mkdir(parents=True, exist_ok=True)
    for b in structures:
        assert b.complex_cif is not None  # with_structures() filtered on exactly this
        shutil.copyfile(b.complex_cif, STRUCT_DIR / b.complex_cif.name)
    counts["structures"] = len(structures)

    # Discovered, not listed: a second vendored library is mirrored the day it
    # arrives, and its licence travels with it because a licence is a file in
    # that directory rather than a name this function knows.
    VENDOR_DIR.mkdir(parents=True, exist_ok=True)
    for src in sorted((WEB_STATIC / "vendor").iterdir()):
        if src.is_file():
            shutil.copyfile(src, VENDOR_DIR / src.name)
            counts["vendor"] += 1

    return counts


def _viewer_block(d: showcase.DesignerShowcase) -> list[str]:
    """The 3-D viewer, as raw HTML the site serves without a server.

    Every URL here is relative to ``docs/assets/js/binder_viewer.js``, because
    that script resolves them against its own location rather than the page's --
    which is what lets one viewer work under ``mkdocs serve`` at ``/``, under
    Pages at ``/bindsight/``, and inside ``bindsight ui`` unchanged.

    Each element is emitted on one line and the block carries no blank lines:
    python-markdown ends a raw HTML block at the first blank line, and a
    half-closed block renders the rest of its own markup as text.
    """
    # Identify the design; do not reprint its score. The table below carries
    # every ipTM next to the caveat that the pre-fix protocol's figures are
    # withdrawn, and tests/test_docs_claims.py enforces that a withdrawn figure
    # never appears further than a paragraph from its retraction. A picker
    # listing twenty scores on one line cannot keep that promise for the
    # twentieth, so it does not make it: the list is ordered best-first and the
    # numbers live where their context does.
    options = "".join(
        f'<option value="{b.binder_id}">{b.binder_id}</option>' for b in d.with_structures()
    )
    host = (
        '<div id="viewer" class="bs-viewer" role="img" data-binder-viewer'
        ' data-viewer-lib="../vendor/3Dmol-min.js"'
        ' data-structure-url="../structures/{id}_complex.cif"'
        ' aria-label="Three-dimensional view of the predicted binder-target complex">'
        '<p class="bs-viewer__fallback">The structure viewer needs JavaScript. Every '
        "complex is also committed as mmCIF under <code>benchmarks/designer_benchmark/"
        "</code>, which is the file this viewer reads.</p></div>"
    )
    return [
        '<div class="bs-viewer-picker"><label for="binder-pick">Design</label>'
        f'<select id="binder-pick" data-binder-picker>{options}</select></div>',
        host,
        '<div class="bs-viewer-legend">'
        '<span><span class="bs-swatch" style="background:#9aa5b1"></span> chain '
        "<strong>T</strong> — the target</span>"
        '<span><span class="bs-swatch" style="background:#0f7d73"></span> chain '
        "<strong>B</strong> — the designed binder</span></div>",
        "",
    ]


