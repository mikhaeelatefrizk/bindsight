from urllib.parse import urlsplit, urlunsplit
from collections.abc import Callable

OUTPUT = pathlib.Path("/kaggle/working")
SCRATCH = pathlib.Path("/kaggle/temp") / ("bindsight-" + HANDLE_ID)
